// FUNCIÓN PARA CONTROLAR CADA CUADRO

function iniciarCuadro(idCuadro, fragmentos, numeroCapitulo) {

    const cuadro = document.getElementById(idCuadro);

    const titulo = cuadro.querySelector(".titulo-fragmento");
    const texto = cuadro.querySelector(".texto-fragmento");
    const indicador = cuadro.querySelector(".indicador");
    const rayitas = cuadro.querySelectorAll(".raya");

    let actual = 0;


    // MOSTRAR EL FRAGMENTO SELECCIONADO

    function mostrarFragmento() {

        const fragmento = fragmentos[actual];

        titulo.textContent = fragmento.titulo;

        indicador.textContent =
            `CAPÍTULO ${numeroCapitulo} · FRAGMENTO ${actual + 1} DE ${fragmentos.length}`;


        // Limpiamos el texto anterior

        texto.replaceChildren();


        // Mostramos los párrafos del fragmento

        fragmento.texto.forEach(function(parrafo) {

            const nuevoParrafo = document.createElement("p");

            nuevoParrafo.classList.add("relato");

            nuevoParrafo.innerHTML = parrafo;

            texto.appendChild(nuevoParrafo);

        });


        // Actualizamos las rayitas

        rayitas.forEach(function(raya, indice) {

            raya.classList.toggle("activa", indice === actual);

        });

    }


    // ACTIVAR LAS RAYITAS

    rayitas.forEach(function(raya) {

        raya.addEventListener("click", function() {

            actual = Number(raya.dataset.fragmento);

            mostrarFragmento();

        });

    });


    // MOSTRAR EL PRIMER FRAGMENTO

    mostrarFragmento();

}


